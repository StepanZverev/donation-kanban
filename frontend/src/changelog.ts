//
// Как поднимать версию (каждый PR, который меняет что-то заметное):
//   новая возможность → +1 к средней цифре, последняя обнуляется: 0.8.2 → 0.9.0;
//   исправление или мелочь → +1 к последней цифре: 0.9.0 → 0.9.1.
